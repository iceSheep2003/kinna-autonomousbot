import { Store } from './infrastructure/sqlite/database.js';
import { composeAgent } from './app/agent.js';
import { sqliteRepositories } from './infrastructure/sqlite/repositories.js';
import { CapabilityRegistry } from './capabilities/registry.js';
import { registerSandbox } from './integrations/builtin.js';
import { DemoModel } from './infrastructure/models/demo.js';
import { ConfigSchema } from './app/config.js';
const store = new Store(':memory:');
const repositories = sqliteRepositories(store);
const registry = new CapabilityRegistry(repositories.operations); registerSandbox(registry);
const config = ConfigSchema.parse({ boundaries: { allowedTools: ['sandbox.observe'] } });
const { runtime } = composeAgent(repositories, new DemoModel(), registry, config);
const now = Date.now();
for (let i = 0; i < 6; i++) await runtime.tick(now + i * 1000);
store.enqueue('dream', 'dream', {}, now + 7000);
await runtime.tick(now + 7000);
await runtime.tick(now + 8000);
console.log(JSON.stringify({ note: '离线模拟，仅验证程序闭环，不代表真实 LLM 能力', self: store.get('subject', 'self'), goals: store.list('goals'), executions: store.list('executions'), memories: store.list('memories'), schedules: store.list('schedules') }, null, 2));
runtime.stop(); store.close();
